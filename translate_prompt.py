# -*- coding: utf-8 -*-
"""Промпты перевода новостей (09.10.2026). Чистый модуль: без сети, fetch_news не импортирует.

Версия 1 — прежний промпт, без изменений (опорная для сравнения).
Версия 2 — после находки владельца 09.10.2026 (Fortune про Гвинн Шотвелл): лёгкая модель
  · перевернула смысл заголовка: «shows billionaires a tax-smart way» → «миллиардеры нашли
    способ» (кто что кому делает);
  · потеряла слово «акции»: «$300 million SpaceX pledge» → «передать 300 миллионов долларов
    SpaceX»;
  · сломала падеж: «give 2 million kids a piece» → «передать более 2 миллионов детей долю».
Версия 2 называет эти ошибки прямо, с примерами, и требует свериться с оригиналом перед
ответом. Какая версия и какая модель работают в бою, решает замер (eval_translation.py).
"""

LANG_NAME = {"ru": "русский", "en": "английский", "es": "испанский",
             "pt": "португальский", "fr": "французский"}

_FORMAT = """Верни ТОЛЬКО JSON без пояснений, ключ — номер новости:
{"1": {"title": "...", "summary": "..."}, "2": {"title": "...", "summary": "..."}}"""

_RULES_V1 = """· Это новостная лента, а не художественный текст: переводи точно и сухо
· Имена, фамилии, должности и названия компаний — правильно и целиком.
  «HD Hyundai Chairman to meet Bill Gates» — это председатель Hyundai
  ВСТРЕТИТСЯ С Гейтсом, а не «председатель Билл Гейтс»
· Идиомы передавай смыслом, а не по словам
· Не сокращай и не пересказывай, не добавляй ничего от себя
· Служебные пометки телеграфных лент — «(4th LD)», «UPDATE 2» — убирай"""

_RULES_V2 = _RULES_V1 + """
· СОХРАНЯЙ, КТО ЧТО КОМУ ДЕЛАЕТ: подлежащее, действие и адресат остаются прежними.
  «Fortune: Shotwell's pledge SHOWS billionaires a tax-smart way to give» — это «обещание
  Шотвелл ПОКАЗЫВАЕТ миллиардерам налогово выгодный способ дарить», а не «миллиардеры
  нашли способ»: «показывает» ≠ «нашли», «миллиардерам» — адресат, а не подлежащее
· Деньги и предмет сделки не теряй и не подменяй. «$300 million SpaceX pledge» — обещание
  передать АКЦИИ SpaceX на 300 млн долларов; слова stock, shares, stake, «акции», «долю»
  сохраняй, «деньги» из них не делай
· Согласуй падежи и числительные как в обычной русской новости. «give more than 2 million
  American kids a piece of her company» — «дать более чем 2 миллионам американских детей
  долю в своей компании» (миллионам — дательный, детей — родительный), а не «передать более
  2 миллионов американских детей долю»
· Заголовок не должен утверждать больше или иное, чем оригинал: «pledge» (обещание) — не
  «передала», «reportedly» — не утверждение, «could» — не «будет»
· Переводи ВЕСЬ данный ТЕКСТ, каждое предложение: первое предложение анонса часто самое
  важное, его нельзя пропускать
· ПЕРЕД ОТВЕТОМ сверь каждый перевод с оригиналом: кто делает, что делает, кому, сколько и
  чего. Нашёл расхождение — исправь"""


def build(items, target_lang, version=1):
    """Текст запроса на перевод пачки новостей. items — словари с title и summary."""
    rules = _RULES_V2 if version >= 2 else _RULES_V1
    numbered = []
    for i, it in enumerate(items, 1):
        numbered.append(f"{i}. ЗАГОЛОВОК: {it.get('title','')}\n   ТЕКСТ: {(it.get('summary') or '')[:900]}")
    return f"""Переведи новости на {LANG_NAME.get(target_lang, target_lang)} язык.

Требования:
{rules}

{_FORMAT}

НОВОСТИ:
{chr(10).join(numbered)}"""
