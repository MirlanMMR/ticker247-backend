"""Тесты цепочки извлечения. Запуск: python test_extract.py — без сети и ключей.

Каждый случай взят из живой находки, а не выдуман: рядом с проверкой указано,
когда и на каком издании это всплыло.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract import (AgencyLeadSanitizer, BeautifulSoup, CreditSanitizer,
                     RepeatedLeadSanitizer,
                     FooterLinkSanitizer, TranslationNoteSanitizer,
                     HeaderNoiseSanitizer, QualityGate, Verdict,
                     extract_article, extract_jsonld, presanitize_dom)

ok = fail = 0


def check(name, got, want):
    global ok, fail
    if got == want:
        ok += 1
    else:
        fail += 1
        print(f"  ✗ {name}\n     ждали: {want!r}\n     вышло: {got!r}")


# Статья намеренно длинная. Предчистка НЕ удаляет узлы, в которых лежит
# заметная доля текста страницы, — иначе на живых сайтах она вырезает статью
# вместе с обёрткой вроде «article__meta-content». Значит и в тесте служебные
# блоки должны быть малой долей, как на настоящей странице
ARTICLE = ("Правительство сообщило о принятом решении в понедельник вечером. "
           "Мера коснётся нескольких тысяч человек и вступит в силу с первого "
           "января следующего года. Ведомство обещает разъяснения позже. "
           "Представители профсоюзов уже заявили о намерении обжаловать эту "
           "инициативу в суде в ближайшие недели после публикации документа. "
           "Профильный комитет парламента рассмотрит поправки на следующей "
           "неделе, сообщил его председатель журналистам в кулуарах заседания. "
           "По оценке ведомства, расходы бюджета вырастут на четыре процента, "
           "а выпадающие доходы регионов будут компенсированы из резервного "
           "фонда в течение трёх лет с момента вступления решения в силу. "
           "Независимые экономисты считают эту оценку заниженной и указывают "
           "на прошлогодний опыт соседней страны, где похожая мера обошлась "
           "казне вдвое дороже первоначального расчёта министерства финансов.")

# ─── JSON-LD ────────────────────────────────────────────────────────────────

LD = ('<html><head><script type="application/ld+json">'
      '{"@context":"https://schema.org","@graph":[{"@type":"NewsArticle",'
      '"headline":"Заголовок","author":{"@type":"Person","name":"Иван"},'
      '"articleBody":"' + ARTICLE + '"}]}'
      '</script></head><body><nav>Меню</nav></body></html>')

check("articleBody достаётся из @graph",
      extract_jsonld(BeautifulSoup(LD, "html.parser")).startswith("Правительство"), True)

check("битая разметка не роняет разбор",
      extract_jsonld(BeautifulSoup(
          '<script type="application/ld+json">{сломано</script>', "html.parser")), "")

check("короткий articleBody не берём (это анонс, а не статья)",
      extract_jsonld(BeautifulSoup(
          '<script type="application/ld+json">'
          '{"@type":"NewsArticle","articleBody":"Коротко."}</script>', "html.parser")), "")

# ─── DOM-предчистка ─────────────────────────────────────────────────────────

DIRTY = """<html><body>
<nav>Главная Спорт Культура Погода</nav>
<div class="byline">Автор, Иван Петров</div>
<div class="reading-time">Время чтения: 5 мин</div>
<article><p>%s</p></article>
<aside class="related">Читайте также</aside>
<div class="social-share">Поделиться</div>
</body></html>""" % ARTICLE

_clean = presanitize_dom(DIRTY.encode())
_txt = _clean.get_text(" ", strip=True)
check("nav вынесен из дерева", "Главная Спорт" in _txt, False)
check("плашка автора вынесена", "Иван Петров" in _txt, False)
check("время чтения вынесено", "Время чтения" in _txt, False)
check("кнопки «поделиться» вынесены", "Поделиться" in _txt, False)
check("сама статья на месте", "Правительство сообщило" in _txt, True)

# Плотность ссылок: блок, где почти все слова в ссылках, — навигация
LINKY = ("<html><body><div>" + "".join(
    f'<a href="/{i}">Раздел номер {i}</a> ' for i in range(12)) +
    "</div><article><p>" + ARTICLE + "</p></article></body></html>")
_t2 = presanitize_dom(LINKY.encode()).get_text(" ", strip=True)
check("блок из одних ссылок вынесен", "Раздел номер 5" in _t2, False)
check("статья рядом с ним уцелела", "Правительство сообщило" in _t2, True)

# ─── Чистильщики ────────────────────────────────────────────────────────────

check("плашка автора срезается, статья остаётся",
      HeaderNoiseSanitizer().apply(
          "Автор, Иван Петров\nОтдел новостей, Лондон\nВремя чтения: 5 мин\n" + ARTICLE
      ).startswith("Правительство"), True)

check("статья без плашки не трогается",
      HeaderNoiseSanitizer().apply(ARTICLE), ARTICLE)

# 24.08, iXBT: «Источник изображения: Autohome» осталось в теле новости
check("кредит изображения убирается",
      "Autohome" in CreditSanitizer().apply(
          ARTICLE + "\nИсточник изображения: Autohome"), False)

check("хвост «Читайте также» отрезается",
      "Читайте также" in FooterLinkSanitizer().apply(
          ARTICLE + "\nЧитайте также\nДругая новость"), False)

check("короткий текст хвостом не режем в ноль",
      FooterLinkSanitizer().apply("Читайте также\nещё"), "Читайте также\nещё")

# ─── Оценка качества ────────────────────────────────────────────────────────

g = QualityGate()
check("нормальная статья проходит", g.evaluate(ARTICLE)[0], Verdict.PASSED)
check("короткий обрывок — звать следующего",
      g.evaluate("Две фразы. Всё.")[0], Verdict.NEEDS_FALLBACK)

# 23.08: trafilatura «спасла» две страницы, и обе оказались заслонами
check("заслон отвергается совсем",
      g.evaluate("Access Denied. You don't have permission to access this page.")[0],
      Verdict.REJECTED)

# 24.08, Le Figaro «DIRECT. Angers-Lille»: в теле оказалось меню сайта
MENU = "\n".join(["Toutes les infos sport", "Tous les formats", "À la une",
                  "Sports", "Émissions", "En plus", "Suivez-nous sur",
                  "A. Bermont (22')", "62'", "SCO", "0", "2", "LIL"] * 3)
check("меню сайта не проходит", g.evaluate(MENU)[0], Verdict.NEEDS_FALLBACK)

check("повторяющиеся строки не проходят",
      g.evaluate("\n".join(["Одна и та же строка вёрстки повторяется."] * 8))[0],
      Verdict.NEEDS_FALLBACK)

# ─── Цепочка целиком ────────────────────────────────────────────────────────

res = extract_article(LD.encode(), "https://example.com/a")
check("цепочка берёт json-ld первым", res.extractor, "json-ld")
check("и признаёт результат годным", res.verdict, Verdict.PASSED)

res2 = extract_article(DIRTY.encode(), "https://example.com/b")
check("без json-ld доходит до разборщика", res2.ok(), True)
check("плашка автора в итог не попала", "Иван Петров" in res2.text, False)

# ─── HTML-подстановки и врезки: находки из ленты 28.08.2026 ─────────────────
#
# Все случаи взяты ИЗ ОПУБЛИКОВАННОЙ ЛЕНТЫ, не выдуманы. Пять новостей из семи
# с замечаниями несли читателю сырьё: &quot;, &nbsp;, &#39;, &apos;, а Sky
# Sports — открытый тег <p> прямо посреди текста.
#
# Почему так вышло: извлекатели отдают текст, уже вынутый из разметки, и
# подстановки они разбирают сами — НО НЕ ВСЕГДА. Когда текст берётся из
# JSON-LD или из атрибута, он через разметку не проходит вовсе и остаётся как
# есть. Оттого четыре случая из семи — французские: там мы чаще берём JSON-LD.

from extract import EntitySanitizer, PromoLineSanitizer, SANITIZERS

_e = EntitySanitizer()
check("кавычки-подстановки разобраны",
      _e.apply('Aucune &quot;avancée&quot;.'), 'Aucune "avancée".')
check("числовая подстановка разобрана",
      _e.apply("d&#39;enquêter sur la mort"), "d'enquêter sur la mort")
check("апостроф разобран",
      _e.apply("casquette &apos;USA&apos;"), "casquette 'USA'")
check("неразрывный пробел убран",
      "\xa0" in _e.apply("requiere.&nbsp; Hansi"), False)
check("сырой тег снят",
      _e.apply("closes. <p>There are talks."), "closes. There are talks.")
# Теги снимаются ПОСЛЕ разбора подстановок: до него их ещё нет
check("двойное экранирование добито",
      _e.apply("&lt;p&gt;Текст статьи."), "Текст статьи.")
check("чистый текст не тронут",
      _e.apply("Обычная строка без разметки."), "Обычная строка без разметки.")

_body = ("Texas agriculture faces a new threat.\n"
         "Subscribe to The Y’all — a weekly dispatch about Texas.\n"
         + "Настоящий текст статьи продолжается и занимает место. " * 4)
_out = PromoLineSanitizer().apply(_body)
check("врезка про рассылку убрана", "Subscribe" in _out, False)
check("статья при этом цела", len(_out) > 200 and "Texas agriculture" in _out, True)
# Если после удаления почти ничего не осталось — правило отступает: строка
# «подпишитесь» лучше, чем пустая новость
check("короткий текст не выпотрошен",
      PromoLineSanitizer().apply("Sign up for our newsletter."),
      "Sign up for our newsletter.")

# Порядок правил — не мелочь: остальные ищут слова в НАЧАЛЕ строки, а
# «&quot;Подпишитесь» началом строки не выглядит
check("подстановки разбираются первыми", SANITIZERS[0].name, "HTML-подстановки")


# ─── Плейлист видеоплеера вместо статьи ─────────────────────────────────────
#
# Находка пользователя 28.08.2026 на NBC News. Вместо новости читатель получил
# расписание роликов и назвал это «программой передач» — точное описание.

from extract import VideoPlaylistSanitizer

_NBC = ("Trump orders Lake Ontario renamed 'Lake America' 01:25.\n"
        "Americans missing in deadly flood disaster 02:08.\n"
        "Now PlayingPatient battles insurance over coverage 03:28.\n"
        "UP NEXTJury deliberates in Lindsay Clancy murder trial 02:20.")
_v = VideoPlaylistSanitizer()
check("плейлист выброшен целиком", _v.apply(_NBC), "")

# Живой текст трогать нельзя ни при каких условиях
_REAL = ("Пациентка судится со страховой компанией из-за отказа оплатить "
         "операцию.\n\nЖенщина обратилась в суд после отказа страховщика.")
check("живой текст не тронут", _v.apply(_REAL), _REAL)

# Смесь: статья со списком роликов в начале — оставляем статью
check("из смеси остаётся статья",
      _v.apply(_NBC + "\n\nНастоящий текст статьи начинается здесь."),
      "Настоящий текст статьи начинается здесь.")

# Одного хронометража мало: он может быть в цитате или в расписании внутри
# новости. Двух довольно — у живого текста так не бывает
check("одна строка с временем не приговор",
      _v.apply("Заседание началось в 14:30.\nСуд продолжит работу завтра."),
      "Заседание началось в 14:30.\nСуд продолжит работу завтра.")

check("порядок: плейлист вторым, после подстановок",
      SANITIZERS[1].name, "плейлист видеоплеера")

# ─── примечание переводчика ────────────────────────────────────────────────
# Найдено 29.08.2026 в испанской ленте: сноску Би-би-си мы не вырезали, а
# перевели вместе с новостью, и читатель получил обещание ссылки, которой нет.
_TN = TranslationNoteSanitizer()

_ES = ("Esta es una traducción de un reportaje de un corresponsal de la BBC. "
       "El original en inglés se puede consultar aquí. En Viena se busca a dos "
       "hombres que robaron de un museo un collar con más de 600 diamantes, "
       "informó la policía el jueves por la tarde.")
check("сноска Би-би-си по-испански снята", _TN.apply(_ES),
      "En Viena se busca a dos hombres que robaron de un museo un collar con "
      "más de 600 diamantes, informó la policía el jueves por la tarde.")

_RU = ("Это перевод материала корреспондента Би-би-си. Оригинал на английском "
       "можно прочитать здесь. В Вене идёт международный розыск двух мужчин, "
       "укравших из музея колье с более чем 600 бриллиантами, сообщила полиция "
       "в пятницу утром.")
check("сноска Би-би-си по-русски снята", _TN.apply(_RU),
      "В Вене идёт международный розыск двух мужчин, укравших из музея колье с "
      "более чем 600 бриллиантами, сообщила полиция в пятницу утром.")

check("сноска отдельным абзацем снята",
      _TN.apply("This is a translation of a BBC correspondent's report.\n"
                "Vienna police are hunting two men who stole a necklace."),
      "Vienna police are hunting two men who stole a necklace.")

# Та же фраза ВНУТРИ текста — часть материала, трогать нельзя: правило не
# должно быть шире своей причины
_INSIDE = "В Вене идёт розыск. Это перевод не при чём, фраза внутри."
check("похожая фраза внутри текста цела", _TN.apply(_INSIDE), _INSIDE)

# Если после сноски почти ничего не остаётся — лучше как было, чем огрызок
_SHORT = "Esta es una traducción de la BBC. El original está aquí. Breve."
check("короткий остаток не режем", _TN.apply(_SHORT), _SHORT)

# ─── выжимка агентства перед телеграфным зачином ───────────────────────────
# Найдено пользователем 29.08.2026: заметка РИА про обезьян на Хайнане шла
# дважды подряд — сперва три тезиса агентства, следом та же новость с зачина.
_AL = AgencyLeadSanitizer()

_RIA = ("Власти провинции Хайнань рекомендовали туристам не заходить глубоко в "
        "тропические леса и охраняемые природные территории.\n\n"
        "Туристам не следует вступать в конфликт с обезьянами.\n\n"
        "ПЕКИН, 29 авг - РИА Новости. Власти китайской островной провинции "
        "Хайнань рекомендовали туристам не заходить глубоко в тропические леса "
        "и не вступать в конфликт с обезьянами, сообщает управление туризма.")
check("выжимка перед зачином снята", _AL.apply(_RIA).startswith("ПЕКИН"), True)

_PLAIN = ("ПЕКИН, 29 авг - РИА Новости. Власти провинции рекомендовали туристам "
          "не заходить в леса и не вступать в конфликт с обезьянами, сообщает "
          "управление туризма со ссылкой на специалистов заповедника.")
check("зачин в начале не трогаем", _AL.apply(_PLAIN), _PLAIN)

_NONE = "Обычная новость без зачина, просто текст про Хайнань и обезьян."
check("текст без зачина цел", _AL.apply(_NONE), _NONE)

# Sputnik присылает заметку ДВАЖДЫ: аннотация с зачином, потом весь текст с
# тем же зачином. Первый стоит в самом начале, поэтому брать надо последний.
_SPUT = ("Sputnik Кыргызстан. БИШКЕК, 30-авг. — Sputnik. «Мадина» базарындагы "
         "өрт чектөөгө алынды. ӨКМ жетекчиси алдын ала маалыматтарга таянып... "
         "30.08.2026, Sputnik Кыргызстан. БИШКЕК, 30-авг. — Sputnik. «Мадина» "
         "базарындагы өрт чектөөгө алынды. ӨКМ жетекчиси Канатбек Чыныбаев "
         "электр зымдары бири-бирине тийишип калганын билдирди. Учурда ал жерде "
         "өрт өчүрүүчү 10 бригада иштеп жатат, кырсыктын кесепеттери жоюлууда.")
_out = _AL.apply(_SPUT)
check("повтор Sputnik снят — берём последний зачин",
      _out.count("Чыныбаев"), 1)
check("после срезки остаётся сам материал", _out.startswith("БИШКЕК"), True)

# ─── лид, склеенный с материалом ───────────────────────────────────────────
# Пользователь 30.08 по заметке iXBT: «нет точки в конце предложения». Точка
# не потерялась — там не конец предложения, а шов: выжимка издания оборвана, и
# следом идёт тот же материал с начала.
_RL = RepeatedLeadSanitizer()

_SEAM = ("С 11 сентября Cyber Resilience Act сделает сообщение об активно "
         "эксплуатируемых уязвимостях обязательным для производителей цифровых "
         "продуктов С 11 сентября в Евросоюзе начнёт действовать требование "
         "Cyber Resilience Act: производители цифровых продуктов должны будут "
         "сообщать об активно эксплуатируемых уязвимостях и инцидентах, а также "
         "о серьёзных сбоях в работе систем и сетей связи.")
check("склейка лида с материалом снята",
      _RL.apply(_SEAM).startswith("С 11 сентября в Евросоюзе"), True)

_DUP = ("Один и тот же текст повторяется дважды подряд без всякой причины. "
        "Один и тот же текст повторяется дважды подряд без всякой причины, и "
        "читатель видит его два раза, что выглядит как поломка приложения. "
        "Ниже идут подробности события, которых в первом куске не было вовсе, "
        "и они занимают ещё несколько строк подряд.")
check("прямой повтор начала снят",
      _RL.apply(_DUP).count("Один и тот же текст"), 1)

# Обычный текст с прописной после строчной — имена собственные, названия —
# трогать нельзя: их в новостях больше, чем швов
_OK = ("В Бишкеке прошёл саммит ШОС. Президенты обсудили дороги и торговлю, "
       "подписали ряд соглашений о сотрудничестве между странами региона.")
check("обычный текст цел", _RL.apply(_OK), _OK)

print(f"\nпройдено {ok}, провалено {fail}")

sys.exit(1 if fail else 0)
