# -*- coding: utf-8 -*-
"""СТОРОЖ: ИИ просматривает собранную ленту пула ГЛАЗАМИ ЧИТАТЕЛЯ перед публикацией (журнал J63).

Корень, который в журнале встречается снова и снова (J1: «шагов чистки несколько, итог не смотрит никто»):
каждый этап конвейера судит одну карточку и свой кусок, а то, что видит читатель, — ленту целиком, по
полкам, с плашками «срочно» и «интересное», — не смотрит никто. Владелец 17.10.2026: «надо просматривать
новости глазами читателя»; «стоит открыть приложение — и тут же натыкаешься на баг». CLAUDE.md, правило 4:
«итог после всех шагов проверяет сторож перед публикацией; сторож — следующая задача».

Сторож видит экран читателя: полки «Местные» / «Новости из…» / «Мировые», что из них срочное, важное,
«интересное», откуда новость и какой страны событие, заголовок и начало текста. Определения (полки, событие,
срочно) ему даёт EDITORIAL.md как системная инструкция — единственное место, где они записаны. Возвращает
только проблемные карточки с кодом проблемы; молчит о нормальных.

РЕЖИМ. По умолчанию «тень» (READER_GUARD=shadow): находки печатаются и пишутся в guard_report.md, лента не
меняется; 2–3 прогона сверяем глазами, сколько находок верны. Потом «live»: снимает карточки, которые не
новость / чужое мелкое / повтор, остальное оставляет. Выключить: READER_GUARD=off.
"""
import json
import re

PROBLEMS = {
    "чужое_мелкое": "внутренняя новость другой страны лежит на «Мировых» или «Новости из…» без последствий за границей "
                    "(уход заместителя директора ведомства США, местная политика и суд чужой страны)",
    "не_новость": "по белому списку события нет: плановый уход «пенсионер вышел на пенсию», день-праздник «Всемирный день…», "
                  "совет, обзор, разбор, анонс без сути",
    "курьёз": "«надо же»: находка, странный факт, исследование без последствий для читателя — место в «Интересном», а не на полке",
    "срочность": "помечена срочной или важной, а будить человека не за что (прошедшее происшествие, кража, мелкая беда)",
    "повтор": "тот же сюжет, что у другой карточки этой ленты (укажи её номер в поле dup)",
    "полка": "не та полка: местное лежит на «Новости из…», мировое на «Местных», событие дома у соседей",
    "анонс": "вместо статьи анонс: две фразы, «обновляется», «подробности позже»",
}
MAX_FINDINGS = 25
PER_SHELF = 45
SHELF_NAME = {"local": "МЕСТНЫЕ", "pool": "НОВОСТИ ИЗ…", "world": "МИРОВЫЕ"}
# Ошибки, на которые указал владелец: даём примерами, а не правилами
EXAMPLES = (
    "• «Заместитель директора Секретной службы США уходит в отставку» (The Hill, МИРОВЫЕ, событие US) — чужое_мелкое, "
    "а ещё не_новость: плановый уход.\n"
    "• «Кортизол оказался другом женской репродуктивной системы» (МИРОВЫЕ, без пометки «интересное») — курьёз.\n"
    "• «Кража кабелей оставила дома без света рядом с отделением полиции» (срочное, МЕСТНЫЕ) — срочность.\n"
    "• «СМИ: девять казахстанцев вывезли из зоны боевых действий» и «Семерых казахстанцев вывезли из зоны боевых "
    "действий» — повтор.\n"
    "• Карточка из двух фраз с «Em atualização» — анонс.\n"
)


def _clip(text, n):
    t = re.sub(r"\s+", " ", str(text or "")).strip()
    return t if len(t) <= n else t[:n].rsplit(" ", 1)[0] + "…"


def screen(items):
    """→ список карточек в порядке экрана читателя: полки по порядку, внутри — свежее выше, до PER_SHELF на полку."""
    shown = []
    for shelf in ("local", "pool", "world"):
        part = [x for x in items if x.get("scope") == shelf and x.get("category") not in ("CURRENCY", "CRYPTO")]
        part.sort(key=lambda x: -(x.get("publishedAt") or 0))
        shown += part[:PER_SHELF]
    return shown


def flags_of(x):
    f = []
    if x.get("category") in ("URGENT", "URGENT_LOCAL_ONLY"):
        f.append("СРОЧНО")
    elif (x.get("priority") or 0) >= 2:
        f.append("важное")
    if x.get("interesting"):
        f.append("интересное")
    return f


def build_prompt(shown, pool, home):
    lines, last = [], None
    for n, x in enumerate(shown, 1):
        if x.get("scope") != last:
            last = x.get("scope")
            lines.append(f"\n=== {SHELF_NAME.get(last, last)} ===")
        flags = ("[" + ", ".join(flags_of(x)) + "] ") if flags_of(x) else ""
        where = x.get("event_where") or x.get("country") or "?"
        lines.append(f"{n}. {flags}{x.get('source', '?')} (событие: {where}) — {_clip(x.get('title'), 140)} — "
                     f"{_clip(x.get('summary'), 150)}")
    legend = "\n".join(f"- {code}: {text}" for code, text in PROBLEMS.items())
    return (
        f"Ты — читатель приложения новостей: открыл ленту пула «{pool}», твоя страна — {home}. Ниже экран целиком, по "
        f"полкам; у карточки видно плашки (СРОЧНО, важное, интересное), издание, страну события, заголовок и начало текста. "
        f"Определения полок, события и срочности — в инструкции. Найди карточки, на которых читатель споткнётся.\n\n"
        f"Проблемы (код: что это):\n{legend}\n\n"
        f"Ошибки, на которые уже указал владелец (примеры):\n{EXAMPLES}\n"
        f"Верни ТОЛЬКО JSON-массив проблемных карточек, например [{{\"n\": 12, \"problem\": \"курьёз\", \"note\": \"почему, "
        f"до 12 слов\"}}, {{\"n\": 31, \"problem\": \"повтор\", \"dup\": 7, \"note\": \"…\"}}]. Нормальные карточки НЕ включай. "
        f"Сомневаешься — не включай: ложная находка хуже пропущенной. Не больше {MAX_FINDINGS} находок; пусто — [].\n"
        + "\n".join(lines))


def parse(raw, total):
    m = re.search(r"\[.*\]", raw or "", re.S)
    data = json.loads(m.group(0))
    out, seen = [], set()
    for f in data:
        n, code = f.get("n"), str(f.get("problem") or "").strip()
        if not isinstance(n, int) or not 1 <= n <= total or code not in PROBLEMS or n in seen:
            continue
        seen.add(n)
        dup = f.get("dup") if isinstance(f.get("dup"), int) and 1 <= f.get("dup") <= total else None
        out.append({"n": n, "problem": code, "note": str(f.get("note") or "")[:120], "dup": dup})
    return out[:MAX_FINDINGS]


def review(items, pool, home, ask):
    """→ (показанные карточки, находки) или None, если ИИ не ответил. ask(prompt) → текст ответа."""
    shown = screen(items)
    if not shown:
        return shown, []
    try:
        return shown, parse(ask(build_prompt(shown, pool, home)), len(shown))
    except Exception:
        return None


# Что снимает боевой режим: только то, что не новость для читателя. Курьёз, срочность и полка пока только
# в отчёте: их чинит соответствующий этап, а не сторож
LIVE_DROPS = {"чужое_мелкое", "не_новость", "повтор"}


def apply(items, shown, findings):
    """Боевой режим. → (карточки без снятых, снятые [(карточка, находка)]). Повтор снимается только с указанным
    двойником (dup): снимаем отмеченную карточку, двойник остаётся."""
    drop = {}
    for f in findings:
        if f["problem"] not in LIVE_DROPS:
            continue
        if f["problem"] == "повтор" and not f.get("dup"):
            continue                          # без указанного двойника не снимаем
        x = shown[f["n"] - 1]
        if x.get("category") in ("URGENT", "URGENT_LOCAL_ONLY") or x.get("vital"):
            continue                          # срочное и жизненно важное сторож не снимает
        drop[id(x)] = (x, f)
    kept = [x for x in items if id(x) not in drop]
    return kept, list(drop.values())
