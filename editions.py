# -*- coding: utf-8 -*-
"""Какие выпуски одной редакции пускать в пул.

BBC в списке источников — шесть строк (News, World, Sport, Русская служба,
Mundo, Brasil), но это одна редакция на разных языках. Мировой источник
раздаётся копией во ВСЕ пулы и переводится на язык пула, поэтому в русской
ленте рядом оказывались BBC Русская служба и BBC Mundo, переведённый с
испанского, и об одном и том же событии выходило два-три материала (01.10.2026:
рейс в Израиль — трижды, казнь Кристы Пайк — дважды). Отсев дублей этого не
ловит: он сравнивает слова заголовков ДО перевода, а у испанского и русского
заголовка общих слов нет; после перевода слова расходятся тоже.

Правило, которое не требует угадывать смысл: если у редакции есть выпуск на
языке пула, выпуски на других языках в этот пул не идут. Русскому читателю —
BBC Русская служба, испанскому — Mundo, португальскому — Brasil, английскому —
News/World/Sport. Там, где выпуска на языке пула нет (французский), остаются все: выбирать не из
чего. Исключение — ONE_EDITION_FAMILIES (France 24): там остаётся английский
(06.10.2026: «FRANCE 24» и «FRANCE 24 FR» выходили в русской ленте рядом).

Вынесено отдельным модулем, чтобы проверять без сети и ключей.
"""

# Язык, на котором выпуск пишет сам. Только для редакций, у которых выпуски
# на разных языках; у остальных (G1, CBN, El País — одна страна и язык) правило
# не нужно. Заводя новый выпуск BBC, впиши его сюда: проверка в
# test_editions.py ругнётся, если выпуск семьи остался без языка.
EDITION_LANG = {
    "BBC News": "en",
    "BBC World": "en",
    "BBC Sport": "en",
    "BBC Русская служба": "ru",
    "BBC Mundo": "es",
    "BBC Brasil": "pt",
    # France 24: английский и французский выпуски одной редакции. 06.10.2026 в
    # русской ленте рядом лежали «FRANCE 24» и «FRANCE 24 FR» — одна история
    # (Израиль и Газа, 7 октября), одно фото
    "France 24": "en",
    "France 24 FR": "fr",
}


# Семьи, где в пуле без «своего» выпуска остаётся только английский
ONE_EDITION_FAMILIES = ("france24",)


def edition_belongs_in_pool(source: str, pool: str, families: dict) -> bool:
    """Нужен ли этому пулу именно этот выпуск редакции.

    families — PUBLISHER_FAMILIES из fetch_news.py (имя семьи → список выпусков).
    Источник вне семьи или выпуск без записанного языка пускаем как раньше.
    """
    members = next((m for m in families.values() if source in m), None)
    mine = EDITION_LANG.get(source)
    if members is None or mine is None:
        return True
    native = {EDITION_LANG[s] for s in members if s in EDITION_LANG}
    if pool in native:
        return mine == pool
    # Выпуска на языке пула нет. Для BBC во французском пуле остаются все
    # (решение 01.10.2026), а для редакций из ONE_EDITION_FAMILIES — один,
    # английский: оба выпуска переводятся на язык пула, а дубль по словам не
    # ловится (06.10.2026: в русской ленте рядом «FRANCE 24» и «FRANCE 24 FR»)
    if "en" in native and any(source in families.get(f, []) for f in ONE_EDITION_FAMILIES):
        return mine == "en"
    return True
