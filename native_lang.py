"""Кыргызский текст помечается языком ky (06.10.2026).

Решение 20.09/30.08: кыргызский язык законен дома в Киргизии — и на любой полке,
в том числе в «Мировых»: кыргызстанец читает новости на родном везде (владелец
06.10.2026: «новость мировая на кыргызском — нормально»). Снимать такие
карточки нельзя.

Беда была в разметке: тексты Kabar.kg по-кыргызски лежали в базе с language="ru"
(язык берётся с настройки пула, а не из текста). Приложение
(NewsPlace.readableFor) принимало их за русские и показывало ВСЕМ читателям
русского пула — в Казахстане, Узбекистане, России, — хотя по правилу кыргызский
читают только дома. Язык определяется по самому тексту (буквы ө ү ң, служебные
слова) и проставляется в language="ky"; дальше работает обычное правило показа.
"""
import re

_KY_LETTERS = re.compile(r"[өүң]")
_KY_WORDS = re.compile(
    r"\b(жана|менен|үчүн|боюнча|болду|болуп|кылды|деп|да|эле|ошондой|аркылуу|"
    r"тарабынан|жөнүндө|катары|бул|анын|алардын)\b")


def looks_kyrgyz(item) -> bool:
    text = ((item.get("title") or "") + " " + (item.get("summary") or "")[:300]).lower()
    # Букв ө, ү, ң в русском тексте нет вовсе — одной достаточно. Казахская и
    # узбекская кириллица их тоже содержит, и для русского пула это то же самое:
    # не русский текст, а значит не для мировой полки
    if _KY_LETTERS.search(text):
        return True
    return len(_KY_WORDS.findall(text)) >= 2


def apply(items, pool_lang: str):
    """→ (список, [перемеченные]). Ничего не снимает. Только для русского пула."""
    if pool_lang != "ru":
        return items, []
    relabeled = []
    for x in items:
        if x.get("category") in ("CURRENCY", "CRYPTO") or x.get("language") == "ky":
            continue
        if looks_kyrgyz(x):
            x["language"] = "ky"
            relabeled.append(x)
    return items, relabeled
