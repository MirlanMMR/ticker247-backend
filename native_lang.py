"""Кыргызский текст — только на местной полке кыргызстанца (06.10.2026).

Владелец, 06.10.2026: «в мировых новости даже на кыргызском языке». Решение
30.08: домашняя лента кыргызстанца держит и новости на родном. Но «родной» —
это местная полка, а не мировая: читатель русского пула в Мировых ждёт русский.

Беда была в разметке: тексты Kabar.kg по-кыргызски лежали в базе с language="ru"
(язык берётся с настройки пула, а не из текста), поэтому приложение
(NewsPlace.readableFor) принимало их как русские и показывало везде.

Здесь два действия, оба без ИИ:
  1. язык карточки определяется по самому тексту (буквы ө ү ң и служебные слова)
     и проставляется в language="ky";
  2. кыргызская карточка вне полки local снимается: переводить её ради мировой
     полки не будем, а показывать нечитаемой нельзя.
"""
import re

_KY_LETTERS = re.compile(r"[өүң]")
_KY_WORDS = re.compile(
    r"\b(жана|менен|үчүн|боюнча|болду|болуп|кылды|деп|да|эле|ошондой|аркылуу|"
    r"тарабынан|жөнүндө|катары|бул|анын|алардын)\b")


def looks_kyrgyz(item) -> bool:
    text = ((item.get("title") or "") + " " + (item.get("summary") or "")[:300]).lower()
    # Букв ө, ү, ң в русском тексте нет вовсе — одной достаточно. Казахская и
    # узбекская кириллица их тоже содержит, и для русского пула это то же самое:
    # не русский текст, а значит не для мировой полки
    if _KY_LETTERS.search(text):
        return True
    return len(_KY_WORDS.findall(text)) >= 2


def apply(items, pool_lang: str):
    """→ (список, [перемеченные], [снятые]). Только для русского пула."""
    if pool_lang != "ru":
        return items, [], []
    kept, relabeled, dropped = [], [], []
    for x in items:
        if x.get("category") in ("CURRENCY", "CRYPTO") or not looks_kyrgyz(x):
            kept.append(x)
            continue
        if x.get("language") != "ky":
            x["language"] = "ky"
            relabeled.append(x)
        if x.get("scope") != "local":
            dropped.append(x)
            continue
        kept.append(x)
    return kept, relabeled, dropped
