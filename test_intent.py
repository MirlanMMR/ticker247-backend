"""Намерения — не события (intent.py)."""
import sys
from intent import is_intent, mark

ok = fail = 0
def check(name, cond):
    global ok, fail
    if cond: ok += 1; print(f"  ✓ {name}")
    else: fail += 1; print(f"  ✗ {name}")

c = lambda title, **k: dict(title=title, category=k.pop("category", "NEWS"), **k)

# Намерения: собираются, планируют, предложили — карусели не место
check("«планируют построить»", is_intent(c("В Бишкеке планируют построить новую развязку")))
check("«собирается»", is_intent(c("Правительство собирается повысить тарифы")))
check("«предложил»", is_intent(c("Министр предложил объединить системы мониторинга")))
check("«хотят ввести»", is_intent(c("Депутаты хотят ввести новый налог")))
check("«обсудят»", is_intent(c("Парламент обсудит поправки на следующей неделе")) is False)  # будущее время без маркера — ИИ
check("«обсудят» (прямая форма)", is_intent(c("Власти обсудят строительство нового моста")))

check("«призвал объединить» — слова, не событие (Минприроды КР, 06.10.2026)", is_intent(c("Глава Минприроды Кыргызстана призвал объединить системы мониторинга")))

# Факт: решение принято — это событие
check("«утвердили план» — событие", not is_intent(c("Правительство утвердило план строительства развязки")))
check("«суд назначил» — событие", not is_intent(c("Суд назначил слушание, власти планируют обжаловать")))
check("«ввели штрафы» — событие", not is_intent(c("Власти ввели штрафы, а депутаты хотят ужесточить")))

# Жителям: отключения, перекрытия, выплаты — жизненно важное, не метим
check("«отключат воду» — объявление жителям", not is_intent(c("Водоканал планирует отключить воду в трёх районах Бишкека")))
check("жизненно важное не метим", not is_intent(c("Власти планируют эвакуацию жителей", vital=True)))
check("срочное не метим", not is_intent(c("Власти планируют эвакуацию", category="URGENT")))
check("обычная новость без намерения", not is_intent(c("Футболисты выиграли матч в Лиге наций")))

items = [c("Мэрия планирует построить парк"), c("Мэрия построила парк"), c("USD 89", category="CURRENCY")]
check("mark помечает только намерения", [x.get("noEvent") for x in mark(items, "ru")] == [True])
check("ничего не снимает", len(items) == 3)
check("в других пулах не работает", mark([c("The mayor plans to build a park")], "en") == [])
print(f"\nпройдено {ok}, провалено {fail}")
sys.exit(1 if fail else 0)
