# -*- coding: utf-8 -*-
"""Жизненно важное по городу (15.10.2026): ливень на Москву, воздушная тревога в Казани, перевал.

Тесты на ПРАВИЛО: класс «опасная погода / закрытый проезд / воздушная тревога / коммуналка в
определённом городе» и классы ложных срабатываний, найденные на живой ленте."""
import sys

import vital_city as V

ok = fail = 0


def check(name, cond):
    global ok, fail
    if cond:
        ok += 1
    else:
        fail += 1
        print(f"  ✗ {name}")


def it(title, source="Лента", **kw):
    return {"title": title, "source": source, **kw}


def kind(title, source="Лента", **kw):
    return V.vital_kind(it(title, source, **kw))


def city(title, source="Лента", **kw):
    c = V.city_of_item(it(title, source, **kw))
    return c["id"] if c else None


# ── случай владельца: ливень и ветер на Москву ──
check("ливень и ветер на Москву → погода, Москва",
      kind("На Москву надвигается сильный ливень с порывистым ветром") == "weather"
      and city("На Москву надвигается сильный ливень с порывистым ветром") == "RU-MOW")
check("штормовое предупреждение в Москве", kind("МЧС объявило штормовое предупреждение в Москве") == "weather")
check("шквалистый ветер до 20 м/с в Петербурге",
      kind("В Петербурге ожидается сильный ветер до 20 м/с") == "weather"
      and city("В Петербурге ожидается сильный ветер до 20 м/с") == "RU-SPE")
check("град и гроза в Краснодаре", kind("Град и гроза накроют Краснодар вечером") == "weather")
check("метель в Новосибирске", kind("Новосибирск накроет метель") == "weather")
check("оранжевый уровень опасности", kind("В Казани объявлен оранжевый уровень погодной опасности") == "weather")
check("английский: severe storm", kind("Severe storm warning for Dallas tonight") == "weather")
check("испанский: lluvias fuertes", kind("Lluvias fuertes en Ciudad de México esta tarde") == "weather")

# ── ложные срабатывания ──
check("«угрозу безопасности» — не гроза (Engadget, живая лента)",
      kind("Штаты подали в суд на OpenAI за угрозу безопасности детей") is None)
check("обычная погода без опасного явления — не событие", kind("В Москве завтра +5 и небольшой дождь") is None)
check("потепление до +21 — не событие", kind("До +21 градуса: синоптики пообещали рязанцам тепло") is None)
check("годовщина урагана — не «сейчас»", kind("В Москве вспомнили ураган 1998 года") is None)
check("вечер памяти погибшего при атаке БПЛА — не тревога (живая лента)",
      kind("В Перми пройдет вечер памяти поэта, погибшего при атаке БПЛА") is None)
check("ДТП и пробка на улице — ежедневное, не событие (живая лента)",
      kind("В час пик из-за ДТП на Худякова выстроилась большая пробка") is None)
check("текст, а не заголовок, не судим (школьные новости про отопление)",
      kind("Школы переводят на дистант в центре Кургана", summary="из-за отключения отопления") is None)

# ── проезд, воздушная тревога, коммуналка ──
check("перевал: запретили проезд", kind("На перевале Тоо-Ашуу до мая запретили проезд микроавтобусов") == "road")
check("мост перекрыт", kind("В Тюмени перекрыли мост через Туру") == "road")
check("ракетная опасность", kind("В Татарстане дважды за ночь объявляли ракетную опасность") == "air")
check("аэропорт: задержаны рейсы", kind("В аэропорту Казани задержаны 20 рейсов из-за ракетной опасности") == "air")
check("отключение воды в Бишкеке", kind("В Бишкеке отключат воду в нескольких районах") == "utility")
check("без света остались", kind("Без света остались жители Самары") == "utility")

# ── город карточки ──
check("город из издания: «62.ru — Рязань»", city("Завтра отключат свет", "62.ru — Рязань") == "RU-RYA")
check("город из заголовка главнее издания", city("В Казани ураган повалил деревья", "62.ru — Рязань") == "RU-TA")
check("город из начала текста", city("Отключат воду", "Лента", summary="Жители Бишкека останутся без воды") == "KG-BK")
check("падеж: в Бишкеке", city("В Бишкеке закрыли мост") == "KG-BK")
check("Ош — город, «ошибка» — нет", city("Ошибка в расписании") is None and city("В Оше отключат свет") == "KG-OS")
check("Киров — не Кировоград", city("В Кировограде взрыв") is None)
check("«Москвич» — не Москва", city("Новый Москвич вышел на рынок") is None)
check("страна без города — города нет", city("В Киргизии запретили проезд") is None)

# ── отметка: только с городом, потолки, срок ──
now = 1_000_000_000_000
def card(t, src, age_h=1, **kw):
    return {"title": t, "source": src, "publishedAt": now - int(age_h * 3600_000), **kw}

items = [card("В Москве штормовое предупреждение: ливень", "Лента"),
         card("На перевале запретили проезд", "Sputnik KG"),                # города нет
         card("В Москве сильный ветер до 25 м/с", "Лента", age_h=2),
         card("В Москве гроза и град", "Лента", age_h=3),                   # третья по Москве — сверх потолка
         card("В Москве ливень вчера", "Лента", age_h=20)]                  # старая
got = V.mark_vital_city(items, now)
check("отмечено 2 из Москвы (потолок на город)", len(got) == 2 and all(x["city"] == "RU-MOW" for x in got))
check("координаты на карточке", all(abs(x["cityLat"] - 55.7558) < 1e-3 for x in got))
check("без города не отмечаем", not items[1].get("vital"))
check("старше 14 часов не отмечаем", not items[4].get("vital"))
check("категорию и приоритет метка не трогает", all("category" not in x and "priority" not in x for x in got))

many = [card(f"В {n} сильный ливень", "Лента") for n in
        ("Москве", "Казани", "Уфе", "Перми", "Омске", "Самаре", "Тюмени", "Томске", "Липецке", "Рязани", "Туле", "Сочи", "Бишкеке", "Оше")]
check("потолок на пул", len(V.mark_vital_city(many, now)) == V.VITAL_CITY_TOTAL)

# ── лестница уверенности тревог ──
check("нет источников → 0", V.alert_level(set(), False, False) == 0)
check("один чужой источник → 1 (без уведомления)", V.alert_level({"РИА"}, False, False) == 1)
check("одно местное издание → 2", V.alert_level({"116.ru"}, True, False) == 2)
check("один официальный канал → 2, не 3 (взломать можно и его)", V.alert_level({"gov"}, False, True) == 2)
check("два независимых без местного → 2", V.alert_level({"РИА", "РБК"}, False, False) == 2)
check("местное + ещё одно независимое → 3", V.alert_level({"116.ru", "РИА"}, True, False) == 3)
check("официальный + независимое → 3", V.alert_level({"gov", "РИА"}, False, True) == 3)
check("три независимых → 3", V.alert_level({"a", "b", "c"}, False, False) == 3)
check("дубли одного издания считаются один раз", V.alert_level({"116.ru"}, True, False) == 2)

air1 = card("В Татарстане объявили ракетную опасность", "116.ru — Казань")
air2 = card("В аэропорту Казани ограничения из-за ракетной опасности", "РИА Новости", age_h=0.5)
got = V.mark_vital_city([air1, air2], now, family_of=lambda s: s.split(" — ")[0])
check("тревога в Казани: два издания, одно местное → уровень 3", all(x.get("alertLevel") == 3 for x in got))
check("источники названы на карточке", "116.ru" in got[0]["alertSources"] and "РИА Новости" in got[0]["alertSources"])
solo = card("В Рязани объявили ракетную опасность", "РИА Новости")
V.mark_vital_city([solo], now)
check("одно нелокальное издание → уровень 1", solo.get("alertLevel") == 1)
local_solo = card("В Рязани объявили ракетную опасность", "62.ru — Рязань")
V.mark_vital_city([local_solo], now)
check("одно местное → уровень 2", local_solo.get("alertLevel") == 2)
weather = card("В Москве штормовое предупреждение", "Лента")
V.mark_vital_city([weather], now)
check("не тревога — без alertLevel", "alertLevel" not in weather)
check("реестр официальных: проверенные каналы", {"Оперштаб Курской области", "Развожаев (Севастополь)", "Собянин (Москва)"} == V.OFFICIAL_ALERT_SOURCES)
off = card("Курская область: ракетная опасность!", "Оперштаб Курской области")
V.mark_vital_city([off], now)
check("официальный канал сам: город по каналу, уровень 2, не 3", off.get("city") == "RU-KRS" and off.get("alertLevel") == 2)
off2 = card("Курская область: ракетная опасность!", "Оперштаб Курской области")
ria = card("В Курской области объявили ракетную опасность, Курск", "РИА Новости")
V.mark_vital_city([off2, ria], now)
check("официальный + независимое издание → 3", off2.get("alertLevel") == 3 and ria.get("alertLevel") == 3)

print(f"\n{ok} ✓, {fail} ✗")
sys.exit(1 if fail else 0)
