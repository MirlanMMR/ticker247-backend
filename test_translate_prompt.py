# -*- coding: utf-8 -*-
"""Промпт перевода (09.10.2026): версия 1 — прежний боевой текст без изменений, версия 2 — с
правилами против ошибок, найденных владельцем (Fortune / Гвинн Шотвелл)."""
import json
import sys

import translate_prompt as T

ok = fail = 0


def check(name, cond):
    global ok, fail
    if cond:
        ok += 1
    else:
        fail += 1
        print(f"  ✗ {name}")


items = [{"title": "Gwynne Shotwell pledge", "summary": "In a new type of philanthropy..."},
         {"title": "T2", "summary": "x" * 1000}]

# прежний боевой промпт, дословно (снят с main до рефакторинга 09.10.2026)
OLD_HEAD = """Переведи новости на русский язык.

Требования:
· Это новостная лента, а не художественный текст: переводи точно и сухо
· Имена, фамилии, должности и названия компаний — правильно и целиком.
  «HD Hyundai Chairman to meet Bill Gates» — это председатель Hyundai
  ВСТРЕТИТСЯ С Гейтсом, а не «председатель Билл Гейтс»
· Идиомы передавай смыслом, а не по словам
· Не сокращай и не пересказывай, не добавляй ничего от себя
· Служебные пометки телеграфных лент — «(4th LD)», «UPDATE 2» — убирай

Верни ТОЛЬКО JSON без пояснений, ключ — номер новости:
{"1": {"title": "...", "summary": "..."}, "2": {"title": "...", "summary": "..."}}

НОВОСТИ:
"""
v1 = T.build(items, "ru", 1)
check("версия 1 = прежний боевой текст (шапка и формат ответа)", v1.startswith(OLD_HEAD))
check("в формате ответа нет двойных скобок (иначе модель сломает JSON)", "{{" not in v1)
check("тело: номера, заголовки и тексты", "1. ЗАГОЛОВОК: Gwynne Shotwell pledge" in v1 and "2. ЗАГОЛОВОК: T2" in v1)
check("текст обрезается на 900 знаков, как прежде", ("x" * 900) in v1 and ("x" * 901) not in v1)
check("формат ответа — настоящий JSON-образец", json.loads(v1.split("номер новости:\n")[1].split("\n\nНОВОСТИ")[0])["1"] == {"title": "...", "summary": "..."})

v2 = T.build(items, "ru", 2)
for must in ("КТО ЧТО КОМУ ДЕЛАЕТ", "ПОКАЗЫВАЕТ", "АКЦИИ SpaceX", "дательный", "ВЕСЬ данный ТЕКСТ", "ПЕРЕД ОТВЕТОМ"):
    check(f"версия 2 содержит правило «{must}»", must in v2)
check("версия 2 включает все правила версии 1", all(line in v2 for line in ("переводи точно и сухо", "«(4th LD)», «UPDATE 2»")))
check("версия 2 длиннее версии 1 только на правила, не на данные", v2.endswith(v1.split("НОВОСТИ:\n")[1]))
check("версия по умолчанию — 1", T.build(items, "ru").startswith(OLD_HEAD))

for lang, name in {"es": "испанский", "pt": "португальский", "fr": "французский", "en": "английский"}.items():
    check(f"язык {lang} называется словом, а не кодом", f"Переведи новости на {name} язык." in T.build(items, lang, 1))

print(f"{ok} ok, {fail} fail")
sys.exit(1 if fail else 0)
