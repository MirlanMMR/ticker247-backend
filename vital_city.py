CITIES = {cid: {"id": cid, "lat": lat, "lon": lon,
                "rx": re.compile(r"(?<![а-яёa-z\-])(?:" + rx + r")(?![а-яёa-z])", re.I)}
          for cid, lat, lon, rx in _RAW}

# «62.ru — Рязань»: город после тире в названии издания
_SOURCE_CITY = re.compile(r"\s[—–-]\s*(.+?)\s*$")


def _find(text):
    """Город, названный в тексте раньше всех; None, если ни один не назван."""
    best = None
    for c in CITIES.values():
        m = c["rx"].search(text or "")
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), c)
    return best[1] if best else None


def city_of_item(item):
    """Город события: из издания («62.ru — Рязань»), иначе из заголовка, иначе из начала текста.

    Издание главнее: городское издание пишет о своём городе, даже если в заголовке города нет.
    Но если заголовок называет ДРУГОЙ город («Казанские власти…» в рязанском издании),
    верим заголовку: он про то, где произошло.
    """
    src = (item.get("source") or "")
    m = _SOURCE_CITY.search(src)
    src_city = _find(m.group(1)) if m else None
    title_city = _find(item.get("title") or "")
    if title_city:
        return title_city
    if src_city:
        return src_city
    return _find(str(item.get("summary") or "")[:200])


