"""Намерения — не события (владелец, 06.10.2026).

«Эти чиновники почти всегда говорят о том, что собираются сделать. Когда
сделают, тогда и выдадим.» Планы, предложения и обещания — не новость для
карусели, бегущей строки и шторки. Событие наступает, когда решение принято или
дело сделано.

Две опоры: промпт ИИ (fetch_news._filter_chunk, список «нет события») и эта
проверка по заголовку для русского пула — страховка, когда ИИ пропустил.
Результат — только метка noEvent: карточка остаётся в ленте по времени, но не
идёт в карусель, строку и шторку (приложение, util/NoEventMark). Ничего не
снимается.

Не метим: жизненно важное и срочное (объявления жителям — отключения воды и
света, перекрытие дорог, графики, сроки выплат — это тоже «будущее», но для
человека оно важнее многих событий), и заголовок, где намерение уже стало
фактом («суд назначил», «утвердили», «подписал»).
"""
import re

_INTENT = re.compile(
    r"\b(планиру\w*|собира(?:ет|ют)ся|намерен\w*|намерева\w+|хот(?:ят|ел\w*)|"
    r"предлага(?:ет|ют)|предложил\w*|предложат|обсудят|рассмотрят|"
    r"готов(?:ят|ится|ятся)\s+(?:к|ввести|принять|запустить|построить)|"
    r"планируется|будет\s+рассмотрен\w*|в\s+перспективе|вынесут\s+на\s+обсуждение|"
    r"хотят\s+ввести|могут\s+ввести|рассматривает\s+возможность|"
    r"призва\w+|призыва\w+|призвал\w*)\b", re.I)

# Намерение стало фактом или это объявление, важное жителям
_DONE = re.compile(
    r"\b(утвердил\w*|принял\w*|подписал\w*|назначил\w*|ввел\w*|ввёл\w*|запустил\w*|"
    r"открыл\w*|начал\w*|одобрил\w*|вступил\w*|вступает|вступят|"
    # объявления жителям — «будущее», но важное: отключения, перекрытия, эвакуация,
    # выплаты, графики
    r"отключ\w*|перекр\w*|эвакуац\w*|выплат\w*|график\w*)\b", re.I)


def is_intent(item) -> bool:
    title = item.get("title") or ""
    if not _INTENT.search(title):
        return False
    if _DONE.search(title):
        return False
    if item.get("vital") or item.get("category") in ("URGENT", "URGENT_LOCAL_ONLY"):
        return False
    return True


def mark(items, lang):
    """→ [помеченные]. Только русский пул; ничего не снимает."""
    if lang != "ru":
        return []
    marked = []
    for x in items:
        if x.get("category") in ("CURRENCY", "CRYPTO") or x.get("noEvent"):
            continue
        if is_intent(x):
            x["noEvent"] = True
            marked.append(x)
    return marked
