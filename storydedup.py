# -*- coding: utf-8 -*-
"""Один ли это сюжет обзора прессы.

Вынесено из fetch_news.py отдельным модулем ради одного: это можно проверить
БЕЗ сети, ключей и базы. Правило здесь стоит дорого — ошибётся в одну сторону,
и обзор трижды расскажет об одном событии; ошибётся в другую, и склеит разные.
Такое правило обязано иметь проверки.
"""


def _urls(story) -> set:
    return {b.get("url") for b in story.get("blocks", []) if b.get("url")}


def _stems(story) -> set:
    """Корни слов заголовка: первые четыре буквы слов от четырёх букв."""
    import re
    return {w[:4] for w in re.findall(r"[а-яёa-zà-ÿ]{4,}",
                                      (story.get("title") or "").lower())}


def reviewed_extra_urls(stories) -> set:
    """Адреса блоков обзора кроме затравки.

    Затравка остаётся карточкой на полке: пролиставший обзор не глядя
    всё равно увидит событие. Остальные взгляды живут только в обзоре.
    Если их снова выпустить в ленту, одно событие читается трижды —
    как отдельная новость, как «ещё в мире» и как обзор.
    """
    extra = set()
    for st in stories or []:
        if not isinstance(st, dict):
            continue
        for b in (st.get("blocks") or [])[1:]:
            url = (b or {}).get("url")
            if url:
                extra.add(url)
    return extra


def same_story(a, b) -> bool:
    """Один ли это сюжет.

    ОБЩАЯ ССЫЛКА РЕШАЕТ ВСЁ, И ХВАТАЕТ ОДНОЙ. Статья пишется об одном событии;
    если она попала блоком в два сюжета, сюжеты об одном событии. Рассуждение
    почти непробиваемое, и опыт его подтвердил.

    Раньше требовалось ДВЕ общих ссылки, и 28.08.2026 обзор русского пула на
    три четверти состоял из Непала: «Наводнение в Непале», «Обрушение ледника
    в Непале» и «Наводнения в Непале: 469 погибших» жили порознь. Первый и
    второй делили одну статью Sputnik KG, первый и третий — одну статью RTÉ.
    По одной. Порог промахивался ровно на единицу.

    Второе правило — по заголовкам — оставлено для сюжетов, собранных из
    РАЗНЫХ статей об одном событии: общих ссылок у них нет вовсе. Здесь порог
    остаётся в два корня, и снижать его нельзя: одного хватило бы, чтобы
    склеить все новости про одну страну подряд — «Выборы в Молдавии» и
    «Землетрясение в Молдавии» стали бы одним сюжетом.
    """
    ua, ub = _urls(a), _urls(b)
    if ua & ub:
        return True
    sa, sb = _stems(a), _stems(b)
    if sa and sb and len(sa & sb) >= 2:
        return True
    return _blocks_agree(a, b)


def _block_stems(story) -> set:
    """Корни слов из заголовков ВСЕХ блоков сюжета."""
    import re
    out = set()
    for b in story.get("blocks", []):
        out |= {w[:4] for w in re.findall(r"[а-яёa-zà-ÿ]{4,}",
                                          (b.get("title") or "").lower())}
    return out


# Пороги подобраны по живым данным 28.08.2026, не на глаз. Во французском пуле
# «Catastrophe au Népal» и «Crues meurtrières au Népal» дали 14 общих корней и
# 39% пересечения. Все ОСТАЛЬНЫЕ пары сюжетов во всех пяти пулах — не больше
# ЧЕТЫРЁХ общих корней. Запас между «одно событие» и «разные» четырёхкратный,
# и порог поставлен внутри этого запаса, ближе к нижнему краю настоящей пары.
_BLOCK_COMMON_MIN = 8
_BLOCK_SHARE_MIN = 0.25


def _blocks_agree(a, b) -> bool:
    """Об одном ли событии говорят САМИ МАТЕРИАЛЫ, а не имена сюжетов.

    Третий и последний признак, нужен для сюжетов, собранных из РАЗНЫХ статей
    об одном событии и названных по-разному. У «Catastrophe au Népal» и «Crues
    meurtrières au Népal» нет ни общей статьи, ни двух общих слов в названии:
    общее слово одно — «Népal». А блоки у них говорят об одном и том же
    ледниковом паводке, и это видно.

    Двух условий сразу — и числа общих корней, и доли — требуем не для
    строгости. Одно число обманывается длиной: у сюжета из семи блоков корней
    втрое больше, чем у сюжета из двух, и восемь общих там наберётся случайно.
    Доля без числа обманывается наоборот, на коротких сюжетах.
    """
    sa, sb = _block_stems(a), _block_stems(b)
    if not sa or not sb:
        return False
    common = sa & sb
    share = len(common) / min(len(sa), len(sb))
    return len(common) >= _BLOCK_COMMON_MIN and share >= _BLOCK_SHARE_MIN


# Начало текста в запросе о событиях (владелец, 09.10.2026: три карточки об ударе
# по автобусам в Краматорске — NPR, BBC, BBC-трансляция — не склеились).
# По заголовкам ИИ не видит, что «Удар по общественному автобусу в Украине …
# в Киеве» (NPR) и «Авиаудар по Краматорску унес десятки жизней» — одно событие:
# в заголовке NPR города нет. В начале текста есть число жертв, место и участники.
# 0 — выключено (прежнее поведение: только заголовки).
EVENT_SUMMARY_CHARS = 280


def _snippet(item, chars):
    import re
    t = re.sub(r"\s+", " ", str(item.get("summary") or "")).strip()
    if len(t) <= chars:
        return t
    cut = t[:chars].rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:—-") + "…"


def event_lines(items, chars=EVENT_SUMMARY_CHARS):
    """Строки для ИИ: «номер. [издание] заголовок — начало текста».

    Заголовок, повторённый в начале текста, из сниппета не берём: он не добавляет
    сведений. chars=0 — только заголовки."""
    lines = []
    for i, it in enumerate(items):
        head = f"{i + 1}. [{it.get('source', '?')}] {it.get('title', '')}"
        if chars:
            snip = _snippet(it, chars)
            title = str(it.get("title", "")).strip()
            # Текст начат заголовком — заголовок отрезаем, остаток и есть сведения
            if title and snip.lower().startswith(title.lower()[:30]):
                snip = snip[len(title):].lstrip(" :—-.…")
            if len(snip) >= 25:
                head += f" — {snip}"
        lines.append(head)
    return lines


def pick_group_language(langs, counts, pool_lang, local):
    """На каком языке оставить ОДНУ карточку из группы пересказов одного события.

    Решение владельца 09.10.2026 (прежнее, от 20.08: «лучшая на каждом языке»):
    «Более половины украинцев согласны на территориальные уступки» и то же по-кыргызски
    рядом — выбрать один вариант с учётом 50/50.

    local — группа лежит на «Местных»: там держим баланс языков, берём язык, которого
    в ленте сейчас МЕНЬШЕ (counts — счёт остальных местных карточек по языкам);
    при равенстве — язык потока. Вне «Местных» баланса нет: язык потока.
    """
    langs = list(langs)
    if not langs:
        return None
    if not local:
        return pool_lang if pool_lang in langs else langs[0]
    return min(langs, key=lambda l: (counts.get(l, 0), 0 if l == pool_lang else 1))


# ─── Голос текста: назван ли источник и не говорит ли он голосом пресс-службы ─────────
#
# 09.10.2026, владелец: две новости про «Түндүк» и учёт животных — Kaktus.media называет
# источник («сообщает пресс-служба Минводсельпрома») и пересказывает, Knews.kg не
# отредактировал пресс-релиз: текст идёт голосом министерства («просим обратиться…»).
# При выборе из группы пересказов одного события, ПРИ РАВНОМ приоритете, предпочитаем
# карточку с названным источником и не берём ту, что говорит голосом пресс-службы.
import re as _re

_ATTRIBUTION = _re.compile(
    r"(?:сообща(?:ет|ют|ла|ли)|сообщи(?:ли|ла)|по\s+данным|заяви(?:л|ла|ли)|поясни(?:л|ла|ли)|"
    r"отмети(?:л|ла|ли)|говорится|сказано|пресс-служб\w*|according\s+to|said|told|announced|"
    r"según|informó|dijo|segundo|disse|afirmou|selon|a\s+déclaré|indique)", _re.I)

_PRESS_VOICE = _re.compile(
    r"(?<![\w-])(?:просим|просьба|обращаемся|рады\s+сообщить|информируем|сообщаем|напоминаем|"
    r"наш[аеиу]?\s+(?:служб\w*|ведомств\w*|министерств\w*|центр\w*)|"
    r"we\s+(?:are\s+pleased|remind|invite|inform)|please\s+contact|"
    r"le\s+pedimos|pedimos|informamos|nos\s+complace|"
    r"nous\s+(?:vous\s+)?(?:informons|invitons)|veuillez|"
    r"pedimos|solicitamos|temos o prazer)", _re.I)


def source_voice(item) -> int:
    """+1 — источник назван; −1 — голос пресс-службы без названного источника; 0 — иначе."""
    text = str(item.get("summary") or "")[:600]
    attributed = bool(_ATTRIBUTION.search(text))
    if attributed:
        return 1
    return -1 if _PRESS_VOICE.search(text) else 0
