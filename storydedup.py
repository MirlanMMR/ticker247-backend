# -*- coding: utf-8 -*-
"""Один ли это сюжет обзора прессы.

Вынесено из fetch_news.py отдельным модулем ради одного: это можно проверить
БЕЗ сети, ключей и базы. Правило здесь стоит дорого — ошибётся в одну сторону,
и обзор трижды расскажет об одном событии; ошибётся в другую, и склеит разные.
Такое правило обязано иметь проверки.
"""


def _urls(story) -> set:
    return {b.get("url") for b in story.get("blocks", []) if b.get("url")}


def _stems(story) -> set:
    """Корни слов заголовка: первые четыре буквы слов от четырёх букв."""
    import re
    return {w[:4] for w in re.findall(r"[а-яёa-zà-ÿ]{4,}",
                                      (story.get("title") or "").lower())}


def same_story(a, b) -> bool:
    """Один ли это сюжет.

    ОБЩАЯ ССЫЛКА РЕШАЕТ ВСЁ, И ХВАТАЕТ ОДНОЙ. Статья пишется об одном событии;
    если она попала блоком в два сюжета, сюжеты об одном событии. Рассуждение
    почти непробиваемое, и опыт его подтвердил.

    Раньше требовалось ДВЕ общих ссылки, и 28.08.2026 обзор русского пула на
    три четверти состоял из Непала: «Наводнение в Непале», «Обрушение ледника
    в Непале» и «Наводнения в Непале: 469 погибших» жили порознь. Первый и
    второй делили одну статью Sputnik KG, первый и третий — одну статью RTÉ.
    По одной. Порог промахивался ровно на единицу.

    Второе правило — по заголовкам — оставлено для сюжетов, собранных из
    РАЗНЫХ статей об одном событии: общих ссылок у них нет вовсе. Здесь порог
    остаётся в два корня, и снижать его нельзя: одного хватило бы, чтобы
    склеить все новости про одну страну подряд — «Выборы в Молдавии» и
    «Землетрясение в Молдавии» стали бы одним сюжетом.
    """
    ua, ub = _urls(a), _urls(b)
    if ua & ub:
        return True
    sa, sb = _stems(a), _stems(b)
    return bool(sa and sb and len(sa & sb) >= 2)
