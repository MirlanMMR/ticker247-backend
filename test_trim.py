"""Тесты обрезки текста и распознавания страниц-заслонов.

Запуск: python test_trim.py — без сети, без ключей, без базы.
Первый шаг к тому, чтобы журнал видов ошибок превращался в проверки, а не
в память о том, что однажды сломалось.
"""
import sys, os, warnings
warnings.filterwarnings("ignore"); sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from textcut import (trim_to_boundary as T, _looks_blocked as B,
                     strip_title_echo as E, strip_leading_service as S,
                     strip_trailing_service as ST,
                     is_service_lead)

ok = fail = 0
def check(name, got, want):
    global ok, fail
    if got == want: ok += 1
    else:
        fail += 1
        print(f"  ✗ {name}\n     ждали: {want!r}\n     вышло: {got!r}")

# 1. Короткий текст не трогаем
check("короткий не трогаем", T("Две фразы. Вот вторая.", 100),
      "Две фразы. Вот вторая.")

# 2. Режем по границе предложения, а не по счётчику
long = "Первое предложение тут. Второе предложение здесь. Третье уже лишнее."
check("режем по границе", T(long, 30), "Первое предложение тут.")

# 3. Сокращение не считается концом — тот самый случай «оба погибли»
abbr = ("Водитель 1974 г.р. выехал на встречную полосу и столкнулся с "
        "автомобилем, оба погибли. Дальше идёт лишний текст сверх лимита.")
got = T(abbr, 100)
check("сокращение г.р. не граница", got.endswith("оба погибли."), True)

# 4. Восклицание и вопрос — тоже границы, берём БЛИЖАЙШУЮ к лимиту
mix = "Сначала точка. Потом восклицание! Потом вопрос? Потом лишнее."
check("берём последнюю границу", T(mix, 45), "Сначала точка. Потом восклицание!")

# 5. Границы НЕТ В ОКНЕ ЛИМИТА — дотягиваем до ближайшей точки ЗА ним.
#    Правило владельца 21.09.2026: резать абзацами и только после точки.
#    Раньше здесь резали по слову и ставили многоточие — рез всё равно
#    приходился посреди мысли, многоточие лишь извинялось за него.
past = "слово " * 30 + "конец фразы. " + "ещё слова " * 30
got = T(past, 100)
check("дотягиваем до точки за лимитом", got.endswith("конец фразы."), True)
check("и не режем посреди слова", got.rstrip("…").rstrip().endswith("."), True)

# 5б. Точки нет во всём тексте вовсе (перечень без точек, дамп таблицы) —
#     резать не по чему, отдаём целиком. Длиннее лимита, зато не разрезано.
nb = "слово " * 60
got = T(nb, 100)
check("нет точки вовсе → не режем", len(got) > 100, True)

# 6. Граница слишком рано — не схлопываем текст до огрызка
early = "Да. " + "длинное предложение без конца " * 20
got = T(early, 300)
check("ранняя граница не годится", got != "Да.", True)

# 7. Пять языков: латиница с диакритикой
fr = "Le président a signé le décret aujourd'hui. Voici la suite du texte inutile."
check("французский", T(fr, 50), "Le président a signé le décret aujourd'hui.")
es = "El juez dictó sentencia el lunes. Y aquí sigue texto sobrante."
check("испанский", T(es, 40), "El juez dictó sentencia el lunes.")

# 8. Закрывающая кавычка после точки остаётся при предложении
q = 'Он сказал: «мы уходим». Дальше лишний текст который надо срезать.'
check("кавычка не отрывается", T(q, 30).endswith("»."), True)

