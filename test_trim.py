"""Тесты обрезки текста и распознавания страниц-заслонов.

Запуск: python test_trim.py — без сети, без ключей, без базы.
Первый шаг к тому, чтобы журнал видов ошибок превращался в проверки, а не
в память о том, что однажды сломалось.
"""
import sys, os, warnings
warnings.filterwarnings("ignore"); sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from textcut import trim_to_boundary as T, _looks_blocked as B, strip_title_echo as E

ok = fail = 0
def check(name, got, want):
    global ok, fail
    if got == want: ok += 1
    else:
        fail += 1
        print(f"  ✗ {name}\n     ждали: {want!r}\n     вышло: {got!r}")

# 1. Короткий текст не трогаем
check("короткий не трогаем", T("Две фразы. Вот вторая.", 100),
      "Две фразы. Вот вторая.")

# 2. Режем по границе предложения, а не по счётчику
long = "Первое предложение тут. Второе предложение здесь. Третье уже лишнее."
check("режем по границе", T(long, 30), "Первое предложение тут.")

# 3. Сокращение не считается концом — тот самый случай «оба погибли»
abbr = ("Водитель 1974 г.р. выехал на встречную полосу и столкнулся с "
        "автомобилем, оба погибли. Дальше идёт лишний текст сверх лимита.")
got = T(abbr, 100)
check("сокращение г.р. не граница", got.endswith("оба погибли."), True)

# 4. Восклицание и вопрос — тоже границы, берём БЛИЖАЙШУЮ к лимиту
mix = "Сначала точка. Потом восклицание! Потом вопрос? Потом лишнее."
check("берём последнюю границу", T(mix, 45), "Сначала точка. Потом восклицание!")

# 5. Границы нет вовсе — многоточие, не обрыв на полуслове
nb = "слово " * 60
got = T(nb, 100)
check("нет границы → многоточие", got.endswith("…") and not got.endswith("сло…"), True)

# 6. Граница слишком рано — не схлопываем текст до огрызка
early = "Да. " + "длинное предложение без конца " * 20
got = T(early, 300)
check("ранняя граница не годится", got != "Да.", True)

# 7. Пять языков: латиница с диакритикой
fr = "Le président a signé le décret aujourd'hui. Voici la suite du texte inutile."
check("французский", T(fr, 50), "Le président a signé le décret aujourd'hui.")
es = "El juez dictó sentencia el lunes. Y aquí sigue texto sobrante."
check("испанский", T(es, 40), "El juez dictó sentencia el lunes.")

# 8. Закрывающая кавычка после точки остаётся при предложении
q = 'Он сказал: «мы уходим». Дальше лишний текст который надо срезать.'
check("кавычка не отрывается", T(q, 30).endswith("»."), True)

# 9. Заслоны опознаются
check("Le Monde bot", B("Votre trafic a été identifié comme automatisé (bot). IP: 1.2.3.4"), True)
check("Access Denied", B("Access Denied You don't have permission to access this server."), True)
check("нормальная статья", B("Суд вынес приговор по делу о мошенничестве. " * 5), False)
check("длинная статья про капчу", B("Исследователи обошли captcha. " * 60), False)


# --- границы абзацев ---
para = ("Первый абзац о происшествии, он довольно длинный и содержательный.\n"
        "Второй абзац с подробностями события и деталями.\n"
        "Третий абзац уже за лимитом и должен быть отброшен целиком.")
got = T(para, 120)
check("режем по концу абзаца", got.endswith("деталями.") and "\n" in got, True)
check("не тащим хвост абзаца", "Третий" in got, False)

# Абзац слишком ранний — не жертвуем половиной текста ради ровного края
early_para = "Коротко.\n" + "Очень длинное второе предложение абзаца. " * 8
got = T(early_para, 300)
check("ранний абзац не годится", got.strip() != "Коротко.", True)

# Текст без абзацев ведёт себя как прежде
check("один абзац = граница предложения", T("Раз. Два. Три.", 9), "Раз. Два.")


# --- дубль заголовка в начале текста ---
# 24.08: срезали по длине заголовка при совпадении лишь первых 40 знаков —
# «Конакр» исчезало, читатель видел «и, столице Гвинеи, сообщило…»
gui_t = "По меньшей мере 30 человек погибли в результате оползня на свалке в столице Гвинеи"
gui_b = ("По меньшей мере 30 человек погибли в результате оползня на свалке в Конакри, "
         "столице Гвинеи, сообщило в воскресенье правительство. Ещё шесть ранены.")
check("лид с подробностями не режем", E(gui_t, gui_b), gui_b)
check("обрубка на полуслове нет", E(gui_t, gui_b).startswith("и,"), False)

check("точный дубль срезаем",
      E("Суд вынес приговор", "Суд вынес приговор. Подсудимый получил пять лет."),
      "Подсудимый получил пять лет.")

check("пересказ без новизны срезаем",
      E("Цены на бензин выросли на десять процентов",
        "Цены на бензин выросли на 10 процентов. Об этом сообщили в министерстве."),
      "Об этом сообщили в министерстве.")

check("чужой текст не трогаем",
      E("Суд вынес приговор", "Совсем другая новость про завод."),
      "Совсем другая новость про завод.")

check("одна фраза целиком не исчезает",
      E("Суд вынес приговор", "Суд вынес приговор."),
      "Суд вынес приговор.")


# ─── Имя издания на языке читателя ──────────────────────────────────────────
#
# Находка 28.08.2026: во ВСЕХ четырёх нерусских пулах стояло «BBC Русская
# служба» — по четыре новости в каждом. Заголовок переводился, имя издания
# ехало из настроек кириллицей.

from textcut import display_source

check("кириллица уходит из имени в чужом пуле",
      display_source("BBC Русская служба", "es"), "BBC")
check("во всех нерусских пулах одинаково",
      {display_source("BBC Русская служба", l) for l in ("en", "es", "pt", "fr")},
      {"BBC"})
check("в русском пуле имя не трогаем",
      display_source("BBC Русская служба", "ru"), "BBC Русская служба")
check("латинское имя не трогаем", display_source("BBC News", "pt"), "BBC News")
check("точки и цифры уцелели", display_source("24.kg", "es"), "24.kg")
# Имя без латинской части не переименовать выбрасыванием букв, а безымянная
# новость хуже новости с непонятным именем
check("целиком кириллическое имя оставляем как есть",
      display_source("Кактус", "en"), "Кактус")
check("пустое имя не роняет проверку", display_source("", "fr"), "")


# ─── Сколько новости показывать: мера — абзац, знак — ориентир ─────────────
#
# Решение пользователя 28.08.2026: «я против замеров количеством знаков» и
# «нужна гибкая система, плюс-минус больше-меньше ничего страшного».

from textcut import lead

_S = "Спасательные команды продолжают поиски в пострадавшем районе страны. "

# Целые абзацы: перебор допустим, разрезанный пополам абзац — нет
_MANY = "\n\n".join([_S * 3 for _ in range(5)])
_got = lead(_MANY)
check("набираем целыми абзацами", _got.count("\n\n") + 1, 4)
check("хвостовых пробелов не остаётся", _got == _got.strip()
      and "  " not in _got.replace("\n", ""), True)
check("абзац не разрезан пополам", _got.endswith("страны."), True)
check("абзацы в итоге сохранились", "\n\n" in _got, True)

# Недобор — не беда: уложилась в один абзац, значит новость такая и есть
check("двухабзацный текст не трогаем",
      lead("Первый абзац.\n\nВторой абзац."), "Первый абзац.\n\nВторой абзац.")
check("короткую новость не режем",
      lead("Трамп намерен переименовать озеро Онтарио."),
      "Трамп намерен переименовать озеро Онтарио.")
check("пустое переживается", lead(""), "")

# Так выходит у БОЛЬШИНСТВА: 252 текста из 309 в ленте 28.08 были одним
# куском. Без оговорки про предложения правило молча пропускало бы всё
_ONE = _S * 12
check("одним абзацем — набираем предложениями", len(lead(_ONE)) < len(_ONE), True)
check("и тоже целыми", lead(_ONE).endswith("страны."), True)

# Потолки — про жанр, а не про длину, и стоят выше ориентира
check("совсем короткие абзацы не набираются без конца",
      lead("\n\n".join(f"Абзац {i}." for i in range(1, 20))).count("\n\n") + 1, 5)

print(f"\nпройдено {ok}, провалено {fail}")
sys.exit(1 if fail else 0)
