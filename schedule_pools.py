# -*- coding: utf-8 -*-
"""Расписание обновления ленты по поясам читателей (09.10.2026; четыре прогона — 15.10.2026).

РЕШЕНИЕ ВЛАДЕЛЬЦА (09.10): «рассчитать обновление для часовых поясов — утром, в обед и после
обеда». 15.10: «раздели мир на часовые пояса, только не 24, а скажем 8; три прогона на пул в
дневное время самых больших поясов пула; запуск через внешний планировщик» — и затем «не 3, а 4».

ВОСЕМЬ ПОЯСОВ ПО ТРИ ЧАСА (центр пояса — смещение от UTC, часов):
  −9  Аляска, Гавайи (−10…−8)             +3  Европа, Москва, Турция, Восточная Африка (+2…+4)
  −6  США: центр, горы, запад; Мексика;   +6  Кавказ, Казахстан, Кыргызстан, Узбекистан,
      Колумбия, Перу, Центральная Америка     Пакистан, Индия, Бангладеш (+4…+7)
  −3  США: восток; Бразилия; Аргентина,   +9  Юго-Восточная Азия, Китай, Япония, Корея,
      Чили, Уругвай (−4…−2)                   Западная Австралия (+7…+10)
   0  Великобритания, Португалия,          +12 Восточная Австралия, Новая Зеландия (+10…+13)
      Западная Африка (−1…+1)

У каждого пула — ДВА самых больших пояса его читателей (POOL_MAIN_BANDS). Четыре слота пула
стоят так, чтобы КАЖДЫЙ из его главных поясов получил их все в свой день, с 8:00 до 21:00 по
местному времени пояса: утром, в обед, после обеда и вечером. Ночью не обновляем никого из
главных поясов: издания спят, а читатель не открывает.

Деньги: 4 слота × 5 пулов = 20 «пул-прогонов» в сутки (было 15). Один запуск обновляет только
пулы своего слота (режим POOLS в fetch_news.py). Слоты не копят пулы в один запуск сверх трёх.

Запускает слоты ВНЕШНИЙ планировщик (scheduler/worker.js, Cloudflare Worker), потому что
расписание GitHub пропускает запуски (28 из ~290 у дозора за неделю). Строки `cron:` в fetch.yml
остаются запасными (:07 и :37): запуск по расписанию GitHub видит свежую ленту (шлюз
`FRESH_ENOUGH_MIN`) и выходит, ничего не потратив. Минуты нечётные намеренно: запуски ровно в :00
GitHub задерживает сильнее всего.

Таблицу читают fetch.yml (шаг «Какие пулы обновлять»), scheduler/worker.js и test_schedule.py:
он сверяет строки `cron:` в fetch.yml и в scheduler/wrangler.toml с этой таблицей и проверяет,
что каждый слот попадает в дневные часы главных поясов пула.
"""
import sys

ACTIVE_POOLS = ("ru", "en", "es", "pt", "fr")

# Смещение местного времени ЯДРА аудитории пула от UTC, часов (на октябрь 2026). Нужно для
# справки в журнале запуска; слоты считаются по главным поясам (ниже).
POOL_UTC_OFFSET = {"ru": 6, "en": -4, "es": -6, "pt": -3, "fr": 2}

# Восемь поясов: центр (смещение от UTC, часов)
BANDS = (-9, -6, -3, 0, 3, 6, 9, 12)

# Два самых больших пояса читателей каждого пула (по странам языкового пространства; точных данных
# об аудитории по часам нет, их даст Firebase Analytics — тогда этот список уточняется)
POOL_MAIN_BANDS = {
    "ru": (3, 6),      # Россия, Беларусь, Украина · Кыргызстан, Казахстан, Узбекистан, Кавказ
    "en": (-6, -3),    # США и Канада: центр и запад · восток
    "es": (-6, -3),    # Мексика, Колумбия, Перу · Аргентина, Чили
    "pt": (-3, 0),     # Бразилия · Португалия, Ангола
    "fr": (3, 0),      # Франция, Бельгия, Швейцария · Западная Африка, Марокко
}
# «День» пояса: с какого и по какой час местного времени слот допустим (включительно)
DAY_FROM, DAY_TO = 8, 21
# На сколько часов местное время может уйти от расчётного из-за перехода на зимнее время
DST_TOLERANCE_H = 1

# Минуты запуска каждого слота: два запуска, второй — запасной
CRON_MINUTES = (7, 37)

# Слоты по UTC: час → пулы. У каждого пула четыре слота (утро, обед, после обеда, вечер) в дневных
# часах обоих главных поясов; слоты ru и fr/en/es/pt сдвинуты друг от друга, чтобы в одном запуске
# не набиралось больше трёх пулов.
SLOTS_UTC = {
    0: ("es",),            # Мексика 18:00 · Аргентина 21:00
    5: ("ru",),            # Москва 08:00 · Бишкек 11:00
    8: ("ru", "fr"),       # Москва 11:00 · Бишкек 14:00 · Париж 10:00 · Дакар 08:00
    11: ("ru", "fr"),      # Москва 14:00 · Бишкек 17:00 · Париж 13:00 · Дакар 11:00
    12: ("pt",),           # Бразилия 09:00 · Лиссабон 12:00
    14: ("ru", "fr", "en"),  # Москва 17:00 · Бишкек 20:00 · Париж 16:00 · восток США 10:00 · центр 09:00
    15: ("pt", "es"),      # Бразилия 12:00 · Мексика 09:00
    17: ("fr", "en"),      # Париж 19:00 · Дакар 17:00 · восток США 13:00 · центр 12:00
    18: ("pt", "es"),      # Бразилия 15:00 · Мексика 12:00
    20: ("en",),           # восток США 16:00 · центр 15:00
    21: ("pt", "es"),      # Бразилия 18:00 · Мексика 15:00
    23: ("en",),           # восток США 19:00 · центр 18:00
}

# «Полки стран» (теневой режим, ~8 минут, ~$0,04–0,13) — раз в сутки, в первом слоте
COUNTRY_SHELVES_HOUR = 5


def cron_lines():
    """[(строка cron, (пулы…))] — ровно то, что должно стоять в fetch.yml."""
    return [(f"{m} {h} * * *", pools) for h, pools in sorted(SLOTS_UTC.items()) for m in CRON_MINUTES]


def pools_for_cron(expr):
    """Пулы запуска по строке cron (`github.event.schedule`); пусто — неизвестная строка."""
    for line, pools in cron_lines():
        if line == (expr or "").strip():
            return pools
    return ()


def wants_country_shelves(expr):
    parts = (expr or "").split()
    return len(parts) >= 2 and parts[1] == str(COUNTRY_SHELVES_HOUR)


def selected_pools(value, active=ACTIVE_POOLS):
    """Список пулов из переменной POOLS ('ru,fr'). Пусто — все. Незнакомые имена отбрасываем."""
    names = [p.strip().lower() for p in (value or "").replace(";", ",").split(",") if p.strip()]
    chosen = tuple(p for p in active if p in names)
    return chosen if chosen else tuple(active)


def stale_pools(pools, ages_min, threshold_min):
    """Пулы, которым пора обновляться: возраст ленты ≥ порога. Возраст неизвестен — обновляем
    (дешевле ошибки). Нужен шлюзу свежести: запасной запуск слота видит свежую ленту и выходит."""
    return tuple(p for p in pools if ages_min.get(p) is None or ages_min[p] >= threshold_min)


def local_hour(utc_hour, pool):
    return (utc_hour + POOL_UTC_OFFSET[pool]) % 24


def band_hour(utc_hour, band_center):
    """Местный час в поясе с данным центром."""
    return (utc_hour + band_center) % 24


if __name__ == "__main__":
    # Использование в workflow:  python schedule_pools.py "<cron>"           → «ru,fr»
    #                            python schedule_pools.py --shelves "<cron>" → «1» или «»
    args = sys.argv[1:]
    if args and args[0] == "--shelves":
        print("1" if wants_country_shelves(args[1] if len(args) > 1 else "") else "")
    else:
        print(",".join(pools_for_cron(args[0] if args else "")))
