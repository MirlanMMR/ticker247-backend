# -*- coding: utf-8 -*-
"""Расписание обновления ленты по часовым поясам читателей (09.10.2026).

РЕШЕНИЕ ВЛАДЕЛЬЦА: «рассчитать обновление для часовых поясов — утром, в обед и после
обеда; дозор круглосуточно». Раньше раз в два часа обновлялись ВСЕ пулы разом, а
фактически — раза четыре в сутки с дырами до 11 часов (GitHub пропускает плановые
запуски, а задание держалось 105 минут из-за дозора, и очередь отменяла следующие).
Читатель в Бишкеке просыпался к ленте двенадцатичасовой давности.

Теперь у каждого пула три обновления в сутки по ЕГО местному времени:
утро (около 9:00), обед (около 13:00), после обеда (около 17:00). Один запуск обновляет
только те пулы, у которых сейчас слот (режим POOLS в fetch_news.py), поэтому он стоит
в 3–5 раз дешевле полного: 15 «пул-прогонов» в сутки вместо 4 полных.

Каждый слот запускается ДВАЖДЫ (минуты :07 и :37): расписание GitHub ненадёжно, а второй
запуск видит свежую ленту (шлюз `FRESH_ENOUGH_MIN`) и выходит, ничего не потратив.
Минуты нечётные намеренно: запуски ровно в :00 GitHub задерживает сильнее всего.

Таблицу читает fetch.yml (шаг «Какие пулы обновлять») и test_schedule.py — он же сверяет,
что строки `cron:` в fetch.yml соответствуют этой таблице и попадают в местное утро,
обед и вторую половину дня каждого пула.
"""
import sys

ACTIVE_POOLS = ("ru", "en", "es", "pt", "fr")

# Смещение местного времени ЯДРА аудитории пула от UTC, часов (на октябрь 2026).
# ru — Бишкек; en — восток США (летнее время; зимой на час меньше); es — Мексика (без
# перехода); pt — Бразилия; fr — Франция (летнее время до 25 октября, затем +1).
POOL_UTC_OFFSET = {"ru": 6, "en": -4, "es": -6, "pt": -3, "fr": 2}
# На сколько часов местное время может уйти от расчётного из-за перехода на зимнее время
DST_TOLERANCE_H = 1

# Минуты запуска каждого слота: два запуска, второй — запасной
CRON_MINUTES = (7, 37)

# Слоты по UTC: час → пулы. Для каждого пула — три слота:
# около 9:00, 13:00 и 17:00 местного времени.
SLOTS_UTC = {
    3: ("ru",),            # Бишкек 09:00
    7: ("ru", "fr"),       # Бишкек 13:00 · Париж 09:00
    11: ("ru", "fr"),      # Бишкек 17:00 · Париж 13:00
    12: ("pt",),           # Бразилия 09:00
    13: ("en",),           # восток США 09:00
    15: ("es", "fr"),      # Мексика 09:00 · Париж 17:00
    16: ("pt",),           # Бразилия 13:00
    17: ("en",),           # восток США 13:00
    19: ("es",),           # Мексика 13:00
    20: ("pt",),           # Бразилия 17:00
    21: ("en",),           # восток США 17:00
    23: ("es",),           # Мексика 17:00
}

# «Полки стран» (теневой режим, ~8 минут, ~$0,04–0,13) — раз в сутки, в первом слоте
COUNTRY_SHELVES_HOUR = 3


def cron_lines():
    """[(строка cron, (пулы…))] — ровно то, что должно стоять в fetch.yml."""
    return [(f"{m} {h} * * *", pools) for h, pools in sorted(SLOTS_UTC.items()) for m in CRON_MINUTES]


def pools_for_cron(expr):
    """Пулы запуска по строке cron (`github.event.schedule`); пусто — неизвестная строка."""
    for line, pools in cron_lines():
        if line == (expr or "").strip():
            return pools
    return ()


def wants_country_shelves(expr):
    parts = (expr or "").split()
    return len(parts) >= 2 and parts[1] == str(COUNTRY_SHELVES_HOUR)


def selected_pools(value, active=ACTIVE_POOLS):
    """Список пулов из переменной POOLS ('ru,fr'). Пусто — все. Незнакомые имена отбрасываем."""
    names = [p.strip().lower() for p in (value or "").replace(";", ",").split(",") if p.strip()]
    chosen = tuple(p for p in active if p in names)
    return chosen if chosen else tuple(active)


def stale_pools(pools, ages_min, threshold_min):
    """Пулы, которым пора обновляться: возраст ленты ≥ порога. Возраст неизвестен — обновляем
    (дешевле ошибки). Нужен шлюзу свежести: запасной запуск слота видит свежую ленту и выходит."""
    return tuple(p for p in pools if ages_min.get(p) is None or ages_min[p] >= threshold_min)


def local_hour(utc_hour, pool):
    return (utc_hour + POOL_UTC_OFFSET[pool]) % 24


if __name__ == "__main__":
    # Использование в workflow:  python schedule_pools.py "<cron>"           → «ru,fr»
    #                            python schedule_pools.py --shelves "<cron>" → «1» или «»
    args = sys.argv[1:]
    if args and args[0] == "--shelves":
        print("1" if wants_country_shelves(args[1] if len(args) > 1 else "") else "")
    else:
        print(",".join(pools_for_cron(args[0] if args else "")))
