"""Ведомственная скука на «Местных» (владелец, 08.10.2026).

«Слишком много неинтересных новостей, как будто писать больше не о чем:
одни правительственные, ведомственные новости, намерения и отчёты».

Признак (не список заголовков): в заголовке ОФИЦИАЛЬНЫЙ субъект (министр,
служба, мэрия, депутат…) делает РУТИННОЕ действие (проверил, получила,
обсудили, обязали, построят, консультации…), и при этом нет последствия для
людей: ни происшествия, ни ареста, ни жертв, ни срочности. Такая карточка не
событие в жизни читателя — отчёт о работе ведомства.

Что делаем: ничего не снимаем поштучно, а держим ДОЛЮ. На полке «Местные» не
более DULL_SHARE таких карточек (с полом: полка не опустеет — MIN_LOCAL).
Остаются самые весомые (priority, число изданий, свежесть). Остальное — вон.
Только русский пул: в других пулах слова иные, а правила без замера не пишем
(CLAUDE.md, п. 5).
"""
import re

DULL_SHARE = 0.25     # не больше четверти полки
MIN_LOCAL = 12        # меньше этого полку не режем: пустая хуже скучной

# Официальный субъект (русский и кыргызский — Kabar.kg пишет по-кыргызски)
_OFFICIAL = re.compile(
    r"(министр\w*|министерств\w*|ведомств\w*|правительств\w*|кабмин\w*|мэри[яиюей]\w*|"
    r"акимат\w*|депутат\w*|жогорку|комитет\w*|департамент\w*|управлени\w*|агентств\w*|"
    r"служб[аыеу]\b|служб\w+\s+\w+\s+получил|омбудсмен\w*|полпред\w*|аппарат\w*|"
    r"администраци\w*|госкомитет\w*|минприроды|минсельхоз\w*|минздрав\w*|минфин\w*|"
    r"министрлик\w*|министри|кызматы|мамлекеттик|башкармалыгы|мэриясы)", re.I)

# Рутина, скучная и без названного субъекта: ведомство подразумевается
_STRONG = re.compile(
    r"(консультаци\w*|совещани\w*|меморандум\w*|рабоч\w+\s+поездк\w*|ремонтн\w+\s+работ\w*|"
    r"построят|будет\s+построен\w*|планиру\w*|намерен\w*|годовщин\w*|юбилей\w*|"
    r"отчит\w+|отчёт\w*|заслушал\w*|прилетел\w*\s+в|прибыл\w*\s+в|визит\w*|"
    # кыргызский (Kabar.kg)
    r"курулат|камсыздалды|жыйналат|мааракеси|белгиленүүдө|иш\s+сапары|жолугушту|"
    r"талкууланды|текшерди|кабыл\s+алды|ыйгарды)", re.I)

# Рутина слабая: скучна только если делает официальный субъект
_WEAK = re.compile(
    r"(проверил\w*|проверк\w*|получил[аи]?\b|получили|обязал\w*|обсудил\w*|обсудят|"
    r"провёл\w*|провел\w*|проводятся|проводится|поручил\w*|встретил\w*|встреч[аиу]\b|"
    r"посетил\w*|вручил\w*|поздрав\w*|призвал\w*|попросил\w*|предложил\w*|"
    r"состоял[аись]+\b|обеспечен\w*|оснащен\w*|оснащён\w*)", re.I)

# Последствие для людей — не скука, как бы ни звучал субъект
_CONSEQUENCE = re.compile(
    r"(погиб\w*|убит\w*|убил\w*|задержан\w*|арестован\w*|арестов\w*|обвинил\w*|избиени\w*|"
    r"пожар\w*|взрыв\w*|авари\w*|ДТП|эвакуац\w*|отключ\w*|перекр\w*|выплат\w*|штраф\w*|"
    r"скандал\w*|уволен\w*|уволил\w*|отставк\w*|суд\w*|приговор\w*|пострадав\w*|"
    r"жалоб\w*|травл\w*|наказыва\w*|закрыл\w*|запрет\w*|подорож\w*|подешев\w*)", re.I)


def is_dull(item) -> bool:
    title = item.get("title") or ""
    if not (_STRONG.search(title) or (_OFFICIAL.search(title) and _WEAK.search(title))):
        return False
    if _CONSEQUENCE.search(title):
        return False
    if item.get("vital") or item.get("category") in ("URGENT", "URGENT_LOCAL_ONLY"):
        return False
    return True


def _weight(x):
    return (x.get("priority") or 0, x.get("sourceCount") or 1, x.get("publishedAt") or 0)


def cap_dull(items, lang):
    """→ (оставшиеся, снятые). Только русский пул, только полка «Местные»."""
    if lang != "ru":
        return items, []
    local = [x for x in items if x.get("scope") == "local" and not x.get("bridge")]
    dull = [x for x in local if is_dull(x)]
    if not dull:
        return items, []
    # потолок считаем от того, что останется: n_other / (1 - share) — иначе полка
    # из 28 со скукой 12 просела бы лишь до 21, а не до доли 25 %
    others = len(local) - len(dull)
    allowed = max(int(others * DULL_SHARE / (1 - DULL_SHARE)),
                  MIN_LOCAL - others, 0)
    if len(dull) <= allowed:
        return items, []
    drop_ids = {id(x) for x in sorted(dull, key=_weight)[:len(dull) - allowed]}
    kept = [x for x in items if id(x) not in drop_ids]
    gone = [x for x in items if id(x) in drop_ids]
    print(f"  😴 Ведомственное на «Местных» [{lang}]: {len(dull)} из {len(local)}, "
          f"оставлено {allowed}, снято {len(gone)}")
    for x in gone[:6]:
        print(f"       · {x.get('source','?')}: {(x.get('title') or '')[:70]}")
    return kept, gone
